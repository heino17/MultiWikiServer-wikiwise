import { build } from "esbuild";
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));

const entry = join(__dirname, "..", "..", "..", "node_modules", "@serenity-kit", "opaque", "esm", "index.js");
const outFile = join(__dirname, "..", "tiddlers", "library", "opaque.js");

const banner = `/*\\
title: $:/plugins/mws/client/library/opaque
type: application/javascript
module-type: library

Bundled client for the OPAQUE (PAKE) login protocol
(@serenity-kit/opaque). Generated by build/build-opaque.mjs, do not edit.

\\*/

"use strict";

`;

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: "cjs",
  platform: "browser",
  write: false,
});

const output = result.outputFiles[0].text;
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, banner + output);
console.log("opaque bundle written to", outFile, (output.length / 1024).toFixed(1) + " kB");